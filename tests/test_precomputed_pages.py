"""Pre-built default views: used only when enabled, never for a page with widget state, and named predictably."""

from __future__ import annotations

import json
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PROBE = r"""
import gzip, json, sys, tempfile
from pathlib import Path
from server import runner
tmp = Path(tempfile.mkdtemp())
runner.PRECOMPUTED = tmp
name = runner.precomputed_name("wc", "home", "odi-2023")
(tmp / name).write_bytes(gzip.compress(b'{"slug": "home", "marker": 1}'))
out = {"name": name, "all": runner.precomputed_name("ct", "teams", None)}
out["enabled_hit"] = (runner._precomputed("wc", "home", {"id": "odi-2023"}) or b"").decode()
out["other_edition"] = runner._precomputed("wc", "home", {"id": "odi-2019"})
runner.USE_PRECOMPUTED = False
out["disabled"] = runner._precomputed("wc", "home", {"id": "odi-2023"})
print(json.dumps(out))
"""


def _run(env_extra: dict[str, str]) -> dict:
    env = {**os.environ, **env_extra}
    r = subprocess.run([sys.executable, "-c", PROBE], cwd=ROOT, env=env, capture_output=True, text=True, timeout=240)
    assert r.returncode == 0, r.stderr[-800:]
    return json.loads(r.stdout.strip().splitlines()[-1])


def test_precomputed_lookup_when_enabled() -> None:
    out = _run({"CRICKET_PRECOMPUTED": "1"})
    assert out["name"] == "wc__home__odi-2023.json.gz" and out["all"] == "ct__teams__all.json.gz"
    assert json.loads(out["enabled_hit"])["marker"] == 1
    assert out["other_edition"] is None  # only the exact (competition, page, edition) is served
    assert out["disabled"] is None  # switched off: always computed live


def test_precomputed_is_off_by_default_locally() -> None:
    env = {k: v for k, v in os.environ.items() if k not in ("VERCEL", "CRICKET_PRECOMPUTED")}
    r = subprocess.run(
        [sys.executable, "-c", "from server import runner; print(runner.USE_PRECOMPUTED)"],
        cwd=ROOT, env=env, capture_output=True, text=True, timeout=240,
    )
    assert r.stdout.strip().splitlines()[-1] == "False"


def test_shipped_precomputed_pages_cover_every_default_view() -> None:
    d = ROOT / "server" / "precomputed"
    if not d.exists():
        return  # generated by scripts/precompute_pages.py for a deployment
    names = {f.name for f in d.glob("*.json.gz")}
    assert "wc__home__all.json.gz" in names and "wtc__ml__wtc-2023.json.gz" in names
    assert not any(n.startswith("wc27__") and not n.startswith("wc27__home") for n in names)
