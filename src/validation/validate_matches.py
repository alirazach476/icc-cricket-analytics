"""Match-level rules."""

from __future__ import annotations

from src.validation.rules import Rule

M = "matches m"
KEY = "m.match_id"
PLAYED = "m.result_type = 'RESULT' and coalesce(m.result_margin, '') not ilike '%walkover%'"
DECISIVE = (
    "m.result_type = 'RESULT' and coalesce(m.result_margin, '') not ilike 'Match tied%' "
    "and coalesce(m.result_margin, '') not ilike '%walkover%'"
)

RULES: list[Rule] = [
    Rule(
        "matches.unique_fixture",
        "matches",
        "uniqueness",
        "critical",
        "no other match has the same date and the same two teams",
        M,
        "exists (select 1 from matches o where o.match_date = m.match_date and o.match_id <> m.match_id "
        "and least(o.team1_id, o.team2_id) = least(m.team1_id, m.team2_id) "
        "and greatest(o.team1_id, o.team2_id) = greatest(m.team1_id, m.team2_id))",
        key=KEY,
    ),
    Rule(
        "matches.teams_present",
        "matches",
        "completeness",
        "critical",
        "both teams are recorded",
        M,
        "m.team1_id is null or m.team2_id is null",
        key=KEY,
    ),
    Rule(
        "matches.venue_present",
        "matches",
        "completeness",
        "major",
        "venue is recorded",
        M,
        "m.venue is null or trim(m.venue) = ''",
        key=KEY,
    ),
    Rule(
        "matches.toss_recorded_when_played",
        "matches",
        "completeness",
        "minor",
        "toss decision is recorded for played matches",
        M,
        "m.toss_decision is null",
        where=PLAYED,
        key=KEY,
    ),
    Rule(
        "matches.winner_recorded_when_decisive",
        "matches",
        "completeness",
        "major",
        "a decisive result (not a tie or walkover) has a winner_id",
        M,
        "m.winner_id is null",
        where=DECISIVE,
        key=KEY,
    ),
    Rule(
        "matches.tiebreak_winner_recorded",
        "matches",
        "completeness",
        "minor",
        "a tie decided by super over / boundary count / eliminator stores the winner in winner_id",
        M,
        "m.winner_id is null",
        where="m.result_type = 'RESULT' and m.result_margin ilike 'Match tied%won%'",
        key=KEY,
    ),
    Rule(
        "matches.player_of_match_recorded",
        "matches",
        "completeness",
        "minor",
        "player of the match is recorded for played matches",
        M,
        "m.player_of_match_id is null",
        where=PLAYED,
        key=KEY,
    ),
    Rule(
        "matches.scorecard_complete_when_played",
        "matches",
        "completeness",
        "minor",
        "scorecard_status is 'complete' for played matches",
        M,
        "m.scorecard_status <> 'complete'",
        where=PLAYED,
        key=KEY,
    ),
    Rule(
        "matches.date_in_tournament_window",
        "matches",
        "validity",
        "critical",
        "match date lies within the tournament's start and end dates",
        "matches m join tournaments t on t.tournament_id = m.tournament_id",
        "m.match_date < t.start_date or m.match_date > t.end_date",
        key=KEY,
    ),
    Rule(
        "matches.teams_differ",
        "matches",
        "validity",
        "critical",
        "team1 and team2 are different teams",
        M,
        "m.team1_id = m.team2_id",
        key=KEY,
    ),
    Rule(
        "matches.result_type_valid",
        "matches",
        "validity",
        "major",
        "result_type is RESULT, NO RESULT or ABANDONED",
        M,
        "m.result_type not in ('RESULT', 'NO RESULT', 'ABANDONED')",
        key=KEY,
    ),
    Rule(
        "matches.toss_decision_valid",
        "matches",
        "validity",
        "major",
        "toss decision is bat or field",
        M,
        "m.toss_decision not in ('bat', 'field')",
        where="m.toss_decision is not null",
        key=KEY,
    ),
    Rule(
        "matches.ball_by_ball_status_valid",
        "matches",
        "validity",
        "major",
        "ball_by_ball_status is a known value",
        M,
        "m.ball_by_ball_status not in ('complete', 'partial', 'unavailable', 'not_checked')",
        key=KEY,
    ),
    Rule(
        "matches.stage_in_taxonomy",
        "matches",
        "validity",
        "minor",
        "match_stage is a specific stage, not the catch-all 'Other'",
        M,
        "m.match_stage not in ('Group Stage', 'Super Eight', 'Super Six', 'Semifinal', 'Final', 'Third Place')",
        key=KEY,
        note="'Other' holds Super Six / quarterfinal matches; fixed by a stage taxonomy in Stage 4",
    ),
    Rule(
        "matches.winner_is_participant",
        "matches",
        "referential_integrity",
        "critical",
        "winner_id is one of the two teams playing",
        M,
        "m.winner_id not in (m.team1_id, m.team2_id)",
        where="m.winner_id is not null",
        key=KEY,
    ),
    Rule(
        "matches.toss_winner_is_participant",
        "matches",
        "referential_integrity",
        "critical",
        "toss_winner_id is one of the two teams playing",
        M,
        "m.toss_winner_id not in (m.team1_id, m.team2_id)",
        where="m.toss_winner_id is not null",
        key=KEY,
    ),
    Rule(
        "matches.played_match_has_innings",
        "matches",
        "consistency",
        "critical",
        "a played match (not a walkover) has innings",
        M,
        "not exists (select 1 from innings i where i.match_id = m.match_id)",
        where=PLAYED,
        key=KEY,
    ),
    Rule(
        "matches.bbb_status_matches_deliveries",
        "matches",
        "consistency",
        "major",
        "ball_by_ball_status is 'complete' exactly when deliveries exist",
        M,
        "(m.ball_by_ball_status = 'complete') <> exists (select 1 from deliveries d where d.match_id = m.match_id)",
        key=KEY,
    ),
    Rule(
        "matches.winner_named_in_result_text",
        "matches",
        "consistency",
        "minor",
        "the winner's team name starts the result text (e.g. 'India won by ...')",
        "matches m join teams w on w.team_id = m.winner_id",
        "m.result_margin not ilike w.team_name || '%'",
        where="m.result_type = 'RESULT' and m.result_margin not ilike 'Match tied%'",
        key=KEY,
        note="name-format differences ('U.S.A.' vs 'United States of America') cause false positives; "
        "alias team ids (name = id) also fail here",
    ),
]
