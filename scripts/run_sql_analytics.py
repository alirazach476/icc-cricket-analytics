"""Stage 8: run the SQL analytics library on the gold DuckDB and export every result.

    python scripts/run_sql_analytics.py            # all queries -> reports/sql_analytics/*.csv
    python scripts/run_sql_analytics.py --only q01 # one query, printed
Needs the gold DuckDB (scripts/load_warehouse.py) and the dbt models (dbt build in dbt_gold).
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import duckdb

ROOT = Path(__file__).resolve().parents[1]
QUERIES = ROOT / "sql" / "analytics" / "queries.sql"
DB = ROOT / "data" / "warehouse" / "cricket_gold.duckdb"


def parse_queries(text: str) -> list[dict[str, str]]:
    """Split the library into {name, group, question, sql} blocks."""
    out = []
    for block in re.split(r"(?m)^-- name:\s*", text)[1:]:
        name, _, rest = block.partition("\n")
        meta = dict(re.findall(r"(?m)^-- (group|question):\s*(.+)$", rest))
        sql = "\n".join(line for line in rest.splitlines() if not line.startswith("-- ")).strip()
        out.append(
            {
                "name": name.strip(),
                "group": meta.get("group", ""),
                "question": meta.get("question", ""),
                "sql": sql.rstrip(";"),
            }
        )
    return out


def run(only: str | None = None, out_dir: Path | None = None, db: Path = DB):
    queries = parse_queries(QUERIES.read_text(encoding="utf-8"))
    if only:
        queries = [q for q in queries if q["name"].startswith(only)]
    con = duckdb.connect(str(db), read_only=True)
    results = []
    try:
        for q in queries:
            try:
                df = con.execute(q["sql"]).fetchdf()
                err = None
            except Exception as exc:  # noqa: BLE001 - reported, never hidden
                df, err = None, f"{type(exc).__name__}: {str(exc)[:200]}"
            if out_dir is not None and df is not None:
                out_dir.mkdir(parents=True, exist_ok=True)
                df.to_csv(out_dir / f"{q['name']}.csv", index=False)
            results.append({**q, "df": df, "error": err})
    finally:
        con.close()
    return results


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--only", help="run queries whose name starts with this")
    parser.add_argument("--out", type=Path, default=ROOT / "reports" / "sql_analytics")
    args = parser.parse_args()
    results = run(args.only, args.out)
    failed = [r for r in results if r["error"]]
    for r in results:
        rows = "ERROR " + r["error"] if r["error"] else f"{len(r['df'])} rows"
        print(f"{r['name']:42} {r['group']:12} {rows}")
        if args.only and r["df"] is not None:
            print(r["df"].to_string(index=False))
    if not args.only:
        lines = [
            "# SQL analytics index",
            "",
            "Generated by `scripts/run_sql_analytics.py`.",
            "",
            "ODI data starts at the 2003 World Cup, so career figures cover 2003-2023 only.",
            "",
            "| Query | Group | Question | Rows |",
            "|---|---|---|---|",
        ]
        lines += [
            f"| `{r['name']}` | {r['group']} | {r['question']} | "
            f"{'ERROR' if r['error'] else len(r['df'])} |"
            for r in results
        ]
        (args.out / "INDEX.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(results) - len(failed)}/{len(results)} queries ran; results in {args.out}")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
