"""Stage 18: generate docs/data_dictionary.md from the analytics schema spec and the gold Parquet files.

Column names, types, key roles and foreign keys come from code, so the dictionary cannot drift from the
database. A short curated glossary defines the derived metrics whose meaning is not obvious from a name.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.warehouse.analytics_schema import TABLES, pg_type, read_gold  # noqa: E402

GLOSSARY = {
    "legal ball": "A delivery that is not a wide or a no-ball (`is_legal_ball`); six legal balls make an over. `legal_delivery_number` counts them within an innings.",
    "balls faced": "Every delivery except wides (no-balls are faced by the batter).",
    "phase": "T20: powerplay overs 1-6, middle 7-15, death 16-20. ODI: powerplay 1-10, middle 11-40, death 41-50. Super Over deliveries have phase `super_over`.",
    "over_number": "1-based over index.",
    "strike rate": "Runs per 100 balls faced.",
    "economy": "Runs conceded per six legal balls; byes and leg-byes are not charged to the bowler.",
    "bowler wickets": "Dismissals credited to the bowler: excludes run outs, retirements and obstructing the field. `retired hurt` is not a wicket at all.",
    "dot ball": "A legal delivery on which no runs were scored.",
    "Super Over": "Tie-break innings. Kept in fact_innings/fact_deliveries (flagged `is_super_over`) and in fact_super_over_performances, but excluded from all regular statistics.",
    "winner_source": "How the winner was determined: parsed from the result text, derived from scores, or `manual_override` (documented in config/result_overrides.csv).",
    "ball_by_ball_gap_reason": "Why a match has no delivery rows: `not_in_cricsheet_world_cup_bundle`, `no_result_or_abandoned`, `walkover_no_play`.",
    "Elo (features)": "Per-format team rating, start 1500, K=30, updated only after decided matches, using only earlier matches when used as a feature.",
    "synthetic_*": "Tables prefixed `synthetic_` hold random placeholders, flagged `is_synthetic`; never used in real analysis.",
}


def build() -> str:
    L = [
        "# Data dictionary",
        "",
        "Generated by `scripts/build_docs.py` from `src/warehouse/analytics_schema.py` and the gold Parquet files.",
        "Types are PostgreSQL types in the `analytics` schema; DuckDB holds the same tables in schema `gold`.",
        "",
        "## Glossary",
        "",
    ]
    L += [f"* **{k}** - {v}" for k, v in GLOSSARY.items()]
    L += ["", "## Tables", ""]
    for spec in TABLES:
        df = read_gold(ROOT, spec.name)
        fks = {f.column: f"{f.ref_table}.{f.ref_column}" for f in spec.fks}
        L += [
            f"### `{spec.name}` ({spec.kind})",
            "",
            f"One row per {spec.grain}. Primary key: `{', '.join(spec.pk)}`. Rows: {len(df):,}.",
            "",
            "| Column | Type | Key | Null? | References |",
            "|---|---|---|---|---|",
        ]
        for col in df.columns:
            role = "PK" if col in spec.pk else ""
            nullable = "no" if col in spec.pk or col in spec.not_null else "yes"
            L.append(
                f"| `{col}` | {pg_type(col, df[col])} | {role} | {nullable} | {fks.get(col, '')} |"
            )
        if spec.checks:
            L += ["", "Checks: " + "; ".join(f"`{expr}`" for _n, expr in spec.checks)]
        L.append("")
    return "\n".join(L)


def main() -> int:
    out = ROOT / "docs" / "data_dictionary.md"
    out.write_text(build(), encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)} ({len(TABLES)} tables)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
